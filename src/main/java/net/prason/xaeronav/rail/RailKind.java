package net.prason.xaeronav.rail;

/**
 * レールの種類。トロッコの動きが違うものだけを分ける。
 *
 * <p>保存データには{@link #ordinal()}を書くので、並びを変えたり途中に足したりしないこと（足すなら末尾）。
 */
public enum RailKind {
    /** 普通のレール。曲がれる唯一の種類。 */
    RAIL,
    /** パワードレール。通電で加速、非通電はブレーキ。 */
    POWERED,
    /** 検知レール。走りは普通と同じだが、乗ると隣を給電する（直後の非通電パワードが加速に変わる）。 */
    DETECTOR,
    /** アクティベーターレール。通電していると乗っている人を降ろす。 */
    ACTIVATOR,
    /** 他modのレール。速さも働きも分からない。 */
    OTHER
}
